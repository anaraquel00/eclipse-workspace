package Revisao;

public class Variaveis {

	public static void main(String[] args) {
	/**
	 * Aqui sera uma pequena revisao sobre variaveis e como 
	 * melhor utiliza-las e entendê-las!!!
	 * @author Ana Raquel	
	 */
		
	
//Declaraçao de variaveis
//<tipo> <nome da variavel>;
//<tipo> <nome da variavel> = <valor>;	
//tipo inteiro	
	
	int a;  //Declaracao da variavel
	a = 5;  //Atribuiçao de um valor a variavel!
	//Declarando e inicializando a variavel
	int b = 3;
	System.out.println(a + b);
	//Declarar a variavel que vai ter soma de a + b
	int soma = a + b;
	System.out.println(soma);
	}
}
